
# Enteros (int)
edad = 25
cantidad = 100

print("Edad:", edad)
print("Cantidad:", cantidad)


# Flotantes (float)
precio = 9.99
altura = 1.75

print("Precio:", precio)
print("Altura:", altura)


# Cadenas de texto (string)
nombre = "Juan"
mensaje = "¡Hola, mundo!"

print("Nombre:", nombre)
print("Mensaje:", mensaje)


# Booleanos (bool)
es_mayor_de_edad = True
tiene_descuento = False

print("¿Es mayor de edad?:", es_mayor_de_edad)
print("¿Tiene descuento?:", tiene_descuento)