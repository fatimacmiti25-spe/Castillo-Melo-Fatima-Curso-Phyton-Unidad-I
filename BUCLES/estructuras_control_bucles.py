print("Ejemplos de estructuras de control: bucles")

print("Números del 1 al 5 multiplicados por 2 con bucle for:")
for numero in range(1, 6):
    print(numero * 2)

print("Números del 1 al 5 multiplicados por 2 con bucle while:")
contador = 1

while contador <= 5:
    print(contador * 2)
    contador += 1